export const dictionaries: Record<Locale, Dict> = { en, zh };

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (!vars) return template;
  return Object.entries(vars).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

const literalToKey = new Map<string, string>();
{
  const grouped = new Map<string, { key: string; zh: string }[]>();
  for (const [key, value] of Object.entries(en)) {
    const list = grouped.get(value) ?? [];
    list.push({ key, zh: zh[key] ?? value });
    grouped.set(value, list);
  }
  for (const [value, list] of grouped) {
    const chinese = new Set(list.map((item) => item.zh));
    if (chinese.size === 1) literalToKey.set(value, list[0].key);
  }
}

export function translateLiteral(locale: Locale, text: string) {
  if (!text || locale === "en") return text;
  const key = literalToKey.get(text);
  if (!key) return text;
  return dictionaries[locale][key] ?? text;
}
